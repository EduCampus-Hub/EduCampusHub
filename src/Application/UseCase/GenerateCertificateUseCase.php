<?php

namespace App\Application\UseCase;

use App\Domain\Model\Certificate;
use App\Application\DTO\CertificateDTO;
use App\Domain\Repository\CertificateRepositoryInterface;
use RuntimeException;

class GenerateCertificateUseCase
{
    public function __construct(
        private readonly CertificateRepositoryInterface $certificateRepository
    ) {}

    public function execute(string $enrollmentId, string $userId, string $coursedId): CertificateDTO
    {
        // Check if a certificate already exists for the given enrollment ID
        $existingCertificate = $this->certificateRepository->findByEnrollment($enrollmentId);
        if ($existingCertificate) {
            throw new RuntimeException('Certificate already exists for this enrollment.');
        }

        // Generate a unique certificate code (you can implement your own logic here)
        $certificateCode = bin2hex(random_bytes(16));

        // Create a new certificate instance
        $certificate = Certificate::create(
            id: 0, // Assuming ID will be generated by the repository or database
            enrollmentId: $enrollmentId,
            userId: $userId,
            coursedId: $coursedId,
            issuedAt: (new \DateTime())->format('Y-m-d H:i:s'),
            certificateCode: $certificateCode
        );

        // Save the certificate to the repository
        $this->certificateRepository->save($certificate);

        // Return a DTO representation of the created certificate
        return new CertificateDTO(
            id: $certificate->id,
            enrollmentId: $certificate->enrollmentId,
            userId: $certificate->userId,
            coursedId: $certificate->coursedId,
            issuedAt: $certificate->issuedAt,
            certificateCode: $certificate->certificateCode
        );
    }
}